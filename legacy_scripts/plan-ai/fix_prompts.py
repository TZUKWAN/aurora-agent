import json

with open('outline_with_prompts.json','r',encoding='utf-8') as f:
    data = json.load(f)

# 补充缺失的 prompt
for sec in data['sections']:
    if not sec.get('prompt') or len(sec['prompt']) < 10:
        title = sec['title']
        sid = sec['id']
        if title == '摘要':
            sec['prompt'] = '请为我撰写本项目的商业计划书摘要。摘要需要高度概括项目背景、产品服务、商业模式、核心优势、市场前景与融资需求。要求语言凝练、逻辑清晰、信息完整，能够独立传达项目核心价值。字数充分展开，不少于1500字。'
        elif title == '公司介绍' and sid == 7:
            sec['prompt'] = '请为我撰写本项目的公司介绍概述。简要介绍公司名称、成立时间、注册资本、使命愿景、核心价值观及发展定位。字数不少于800字。'
        elif title == '产品介绍' and sid == 11:
            sec['prompt'] = '请为我撰写本项目的产品介绍概述。简要介绍产品名称、核心功能、目标用户、解决的核心痛点及主要竞争优势。字数不少于800字。'
        elif title == '项目价值':
            sec['prompt'] = '请为我撰写本项目的社会价值与产业价值总论。从引领教育、带动就业、社会公益、产业促进四个维度综合论述项目的宏观意义与长期价值。字数不少于1500字。'
        elif title == '产品功能1':
            sec['prompt'] = '请为我列出智言大模型服务平台的核心功能模块，包括智能客服、知识问答、内容生成、数据分析等。对每个功能模块进行简要说明，字数不少于800字。'
        elif title == '产品功能3':
            sec['prompt'] = '请为我进一步丰富智言平台第三个核心功能的详细介绍，包括功能定义、解决的问题、实现方案及预期效果。字数不少于1000字。'
        elif title == '产品功能4':
            sec['prompt'] = '请为我进一步丰富智言平台第四个核心功能的详细介绍，包括功能定义、解决的问题、实现方案及预期效果。字数不少于1000字。'
        elif title == '核心技术1':
            sec['prompt'] = '请为我列出智言大模型服务平台最关键的3-5个核心技术，形成一个大纲。字数不少于800字。'
        elif title == '核心技术3':
            sec['prompt'] = '请为我撰写智言平台的第三项核心技术，从技术原理、应用方案和壁垒进行深入说明。字数不少于1200字。'
        elif title == '核心技术4':
            sec['prompt'] = '请为我撰写智言平台的第四项核心技术，从技术原理、应用方案和壁垒进行深入说明。字数不少于1200字。'
        elif title == '知识产权':
            sec['prompt'] = '请为我撰写本项目的知识产权布局与保护策略，包括已申请和计划申请的专利、软件著作权及商业秘密保护措施。字数不少于1000字。'
        elif title == '市场环境分析':
            sec['prompt'] = '请为我分析本项目所处的市场环境，包括宏观环境、行业现状、竞争格局及发展趋势。字数不少于1200字。'
        elif title == '竞品分析' and sid == 36:
            sec['prompt'] = '请为我撰写本项目的竞品分析概述，识别主要竞争者类型并简要说明竞争态势。字数不少于800字。'
        elif title == '运营管理':
            sec['prompt'] = '请为我撰写本项目的运营管理体系，包括组织架构、核心流程、质量管理与绩效考核机制。字数不少于1200字。'
        elif title == '运营分析':
            sec['prompt'] = '请为我分析本项目的运营现状与关键指标，包括用户增长、活跃度、留存率及运营效率。字数不少于1000字。'
        elif title == '合规管理':
            sec['prompt'] = '请为我撰写本项目的合规管理策略，包括制度合规、实践合规及风险应对机制。字数不少于1000字。'
        elif title == '营销战略':
            sec['prompt'] = '请为我撰写本项目的整体营销战略，包括品牌定位、传播策略、渠道规划及资源配置。字数不少于1200字。'
        elif title == '产品定位':
            sec['prompt'] = '请为我撰写本项目的产品定位策略，明确产品的市场层级、目标客户及差异化价值主张。字数不少于1000字。'
        elif title == '定价策略' and sid == 52:
            sec['prompt'] = '请为我撰写本项目的定价策略，分析定价模式、定价方法及价格调整机制。字数不少于1000字。'
        elif title == '定价体系' and sid == 53:
            sec['prompt'] = '请为我撰写本项目的定价体系，详细说明产品价格构成与梯度设计。字数不少于1000字。'
        elif title == '营销目标与规划':
            sec['prompt'] = '请为我设计本项目的营销目标与规划，包括初创期、成长期与成熟期的阶段性目标、策略、打法、预算与KPI。字数不少于1500字。'
        elif title == '财务融资':
            sec['prompt'] = '请为我撰写本项目的财务与融资概况，包括历史财务状况、资金用途及融资规划。字数不少于1000字。'
        elif title == '融资规划':
            sec['prompt'] = '请为我撰写本项目的融资规划，明确融资金额、资金用途、出让股权比例及退出机制。字数不少于1200字。'
        else:
            sec['prompt'] = f'请为我撰写本项目的【{title}】。要求内容详实、逻辑严谨、学术化表达，字数不少于1000字。'

with open('outline_with_prompts.json','w',encoding='utf-8') as f:
    json.dump(data, f, ensure_ascii=False, indent=2)

